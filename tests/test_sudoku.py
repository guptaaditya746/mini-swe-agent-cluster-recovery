"""Tests for Sudoku solver."""
import pytest
from sudoku.solver import Sudoku, solve, is_valid, is_empty, get_candidates


class TestSudoku:
    """Tests for the Sudoku class."""
    
    def test_standard_puzzle(self):
        """Solves a standard puzzle."""
        board = [
            [5, 3, 0, 0, 7, 0, 0, 0, 0],
            [6, 0, 0, 1, 9, 5, 0, 0, 0],
            [0, 9, 8, 0, 0, 0, 0, 6, 0],
            [8, 0, 0, 0, 6, 0, 0, 0, 3],
            [4, 0, 0, 8, 0, 3, 0, 0, 1],
            [7, 0, 0, 0, 2, 0, 0, 0, 6],
            [0, 6, 0, 0, 0, 0, 2, 8, 0],
            [0, 0, 0, 4, 1, 9, 0, 0, 5],
            [0, 0, 0, 0, 8, 0, 0, 7, 9],
        ]
        sudoku = Sudoku(board)
        result = sudoku.solve()
        assert result is not None
        assert sudoku.is_valid()
    
    def test_leaves_solved_valid_board_valid(self):
        """After solving, the board should be valid."""
        board = [
            [5, 3, 0, 0, 7, 0, 0, 0, 0],
            [6, 0, 0, 1, 9, 5, 0, 0, 0],
            [0, 9, 8, 0, 0, 0, 0, 6, 0],
            [8, 0, 0, 0, 6, 0, 0, 0, 3],
            [4, 0, 0, 8, 0, 3, 0, 0, 1],
            [7, 0, 0, 0, 2, 0, 0, 0, 6],
            [0, 6, 0, 0, 0, 0, 2, 8, 0],
            [0, 0, 0, 4, 1, 9, 0, 0, 5],
            [0, 0, 0, 0, 8, 0, 0, 7, 9],
        ]
        sudoku = Sudoku(board)
        sudoku.solve()
        assert sudoku.is_valid()
    
    def test_rejects_invalid_board(self):
        """Rejects boards with conflicts."""
        board = [
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
        ]
        with pytest.raises(ValueError):
            Sudoku(board)
    
    def test_handles_unsolvable_puzzle(self):
        """Handles unsolvable puzzle by returning None."""
        board = [
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
        ]
        sudoku = Sudoku(board)
        result = sudoku.solve()
        assert result is None
        assert not sudoku.is_valid()
    
    def test_is_empty(self):
        """Test is_empty function."""
        board = [
            [1, 2, 3, 4, 5, 6, 7, 8, 9],
            [6, 0, 0, 1, 9, 5, 0, 0, 0],
            [0, 9, 8, 0, 0, 0, 0, 6, 0],
            [8, 0, 0, 0, 6, 0, 0, 0, 3],
            [4, 0, 0, 8, 0, 3, 0, 0, 1],
            [7, 0, 0, 0, 2, 0, 0, 0, 6],
            [0, 6, 0, 0, 0, 0, 2, 8, 0],
            [0, 0, 0, 4, 1, 9, 0, 0, 5],
            [0, 0, 0, 0, 8, 0, 0, 7, 9],
        ]
        sudoku = Sudoku(board)
        assert sudoku.is_empty(1, 1)
        assert not sudoku.is_empty(0, 0)
    
    def test_get_candidates(self):
        """Test get_candidates function."""
        board = [
            [5, 3, 0, 0, 7, 0, 0, 0, 0],
            [6, 0, 0, 1, 9, 5, 0, 0, 0],
            [0, 9, 8, 0, 0, 0, 0, 6, 0],
            [8, 0, 0, 0, 6, 0, 0, 0, 3],
            [4, 0, 0, 8, 0, 3, 0, 0, 1],
            [7, 0, 0, 0, 2, 0, 0, 0, 6],
            [0, 6, 0, 0, 0, 0, 2, 8, 0],
            [0, 0, 0, 4, 1, 9, 0, 0, 5],
            [0, 0, 0, 0, 8, 0, 0, 7, 9],
        ]
        sudoku = Sudoku(board)
        candidates = sudoku.get_candidates(0, 2)
        assert 1 in candidates
        assert 2 in candidates
        assert 4 in candidates
        assert 6 in candidates
        assert 9 in candidates
        assert 3 not in candidates  # 3 is in row 0
        assert 5 not in candidates  # 5 is in row 0
        assert 7 not in candidates  # 7 is in row 0
        assert 8 not in candidates  # 8 is in row 0
        assert 0 not in candidates  # 0 is not a valid candidate
